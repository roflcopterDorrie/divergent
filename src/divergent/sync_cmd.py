"""Generate copy-paste sync shell scripts (never executed by this tool)."""

from __future__ import annotations

import secrets
import shlex
from pathlib import Path

from divergent.compare import ChangeKind, CheckResult, FileResult, VariationResult


def render_sync_script(result: CheckResult, variation: VariationResult) -> str:
    """
    Build a bash script that copies post-commit files from main into *variation*
    and creates a commit with the same message.

    The tool only displays this script; it does not run it.
    """
    if not variation.all_safe:
        raise ValueError("sync script is only available when the variation is fully syncable")

    main = result.main_repo.resolve()
    var = variation.path.resolve()
    commit = result.commit
    delim = f"DIVERGENT_EOF_{secrets.token_hex(8)}"

    lines: list[str] = [
        "#!/usr/bin/env bash",
        "# Generated by divergent — review before running.",
        "# This script is NOT executed by divergent itself.",
        "set -euo pipefail",
        f"cd {shlex.quote(str(var))}",
        "",
    ]

    for f in variation.files:
        lines.extend(_file_commands(main, commit, f))
        lines.append("")

    lines.append(f"git commit -F - <<'{delim}'")
    msg = result.message.rstrip("\n")
    lines.append(msg)
    lines.append(delim)

    return "\n".join(lines) + "\n"


def _file_commands(main: Path, commit: str, f: FileResult) -> list[str]:
    path_q = shlex.quote(f.path)
    main_q = shlex.quote(str(main))
    spec_q = shlex.quote(f"{commit}:{f.path}")

    if f.kind == ChangeKind.DELETED:
        return [
            f"# delete {f.path}",
            f"git rm -f -- {path_q}",
        ]

    parent = str(Path(f.path).parent)
    cmds: list[str] = [f"# {f.kind.value} {f.path}"]
    if parent not in ("", "."):
        cmds.append(f"mkdir -p -- {shlex.quote(parent)}")
    cmds.append(f"git -C {main_q} show {spec_q} > {path_q}")
    cmds.append(f"git add -- {path_q}")
    return cmds
