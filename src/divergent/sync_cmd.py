"""Generate copy-paste sync shell scripts (never executed by this tool)."""

from __future__ import annotations

import shlex
from pathlib import Path
from typing import Any

from divergent.compare import (
    ChangeKind,
    CheckResult,
    FileResult,
    FileStatus,
    VariationResult,
)


def syncable_files(variation: VariationResult) -> list[FileResult]:
    return [f for f in variation.files if f.status == FileStatus.SAFE]


def unsyncable_files(variation: VariationResult) -> list[FileResult]:
    return [f for f in variation.files if f.status != FileStatus.SAFE]


def optional_sync_files(variation: VariationResult) -> list[FileResult]:
    """Unsyncable paths that can still be force-synced (not missing deletes)."""
    return [
        f
        for f in unsyncable_files(variation)
        if not (f.status == FileStatus.MISSING and f.kind == ChangeKind.DELETED)
    ]


def addable_missing_files(variation: VariationResult) -> list[FileResult]:
    """Missing paths that can be created on the variation (not deletes)."""
    return [
        f for f in optional_sync_files(variation) if f.status == FileStatus.MISSING
    ]


def default_synced_paths(variation: VariationResult) -> set[str]:
    return {f.path for f in syncable_files(variation)}


def default_ignored_paths(variation: VariationResult) -> set[str]:
    return {f.path for f in unsyncable_files(variation)}


def render_sync_script(
    result: CheckResult,
    variation: VariationResult,
    *,
    include: list[FileResult] | None = None,
) -> str:
    """
    Build a bash script that:

    1. Creates ``feature/…`` (same name as main) from the variation base branch
    2. Copies or deletes selected files in the working tree for review

    Staging and commit are left to the separate Stage / Commit message boxes.

    By default only syncable (SAFE) files are synced; unsyncable paths are
    ignored. Pass *include* to also sync those paths.

    The tool only displays this script; it does not run it.
    """
    data = sync_script_data(result, variation)
    synced = default_synced_paths(variation)
    if include:
        synced |= {f.path for f in include}
    ignored = {f["path"] for f in data["files"] if f["path"] not in synced}
    script = assemble_sync_script(data, synced, ignored)
    if script is None:
        raise ValueError("sync script requires at least one synced file")
    return script


def sync_script_data(result: CheckResult, variation: VariationResult) -> dict[str, Any]:
    """Structured parts for HTML to rebuild the script when checkboxes change."""
    main = result.main_repo.resolve()
    var = variation.path.resolve()
    commit = result.commit
    base = result.variation_base_branch
    branch = result.main_branch

    header = [
        "#!/usr/bin/env bash",
        "# Generated by divergent — review before running.",
        "# This script is NOT executed by divergent itself.",
        "set -euo pipefail",
        f"cd {shlex.quote(str(var))}",
    ]

    if branch:
        branch_lines = [
            f"BRANCH={shlex.quote(branch)}",
            f"BASE={shlex.quote(base)}",
            "# Create the same feature branch as main, starting from the base branch",
            'if git show-ref --verify --quiet "refs/heads/${BRANCH}"; then',
            '  echo "error: branch ${BRANCH} already exists in $(pwd)" >&2',
            "  exit 1",
            "fi",
            'git switch -c "${BRANCH}" "${BASE}"',
        ]
    else:
        branch_lines = [
            "# WARNING: main was not on a named branch; not creating a feature branch.",
            f"# Ensure you are on a branch based on {base} before continuing.",
        ]

    files = [
        {
            "path": f.path,
            "status": _status_label(f),
            "syncable": f.status == FileStatus.SAFE,
            "kind": f.kind.value,
            "lines": _file_commands(main, commit, f),
        }
        for f in variation.files
    ]

    return {
        "header": header,
        "branch": branch_lines,
        "files": files,
        "commit_message": result.message.rstrip("\n"),
        "subjects": list(result.subjects),
    }


def assemble_sync_script(
    data: dict[str, Any],
    synced: set[str],
    ignored: set[str],
) -> str | None:
    """Join script parts; return None if nothing would be synced."""
    to_sync = [f for f in data["files"] if f["path"] in synced]
    if not to_sync:
        return None

    lines: list[str] = list(data["header"])
    lines.append("")

    ignored_entries = [
        {"path": f["path"], "status": f["status"]}
        for f in data["files"]
        if f["path"] in ignored and f["path"] not in synced
    ]
    pending = [
        {"path": f["path"], "status": f["status"]}
        for f in data["files"]
        if f["path"] not in synced and f["path"] not in ignored
    ]

    if pending:
        lines.append("# Partial sync — skipped (not syncable; often regenerated):")
        for s in pending:
            lines.append(f"#   {s['status']} {s['path']}")
        lines.append("")
    if ignored_entries:
        lines.append("# Ignored (acknowledged, not synced):")
        for s in ignored_entries:
            lines.append(f"#   {s['status']} {s['path']}")
        lines.append("")

    lines.extend(data["branch"])
    lines.append("")

    for f in to_sync:
        lines.extend(f["lines"])
        lines.append("")

    return "\n".join(lines) + "\n"


def _status_label(f: FileResult) -> str:
    return {
        FileStatus.SAFE: "syncable",
        FileStatus.DIVERGED: "diverged",
        FileStatus.MISSING: "missing",
        FileStatus.UNEXPECTED: "unexpected",
    }[f.status]


def _file_commands(main: Path, commit: str, f: FileResult) -> list[str]:
    """Working-tree only: copy or delete files for review (no git add/rm/commit)."""
    path_q = shlex.quote(f.path)
    main_q = shlex.quote(str(main))
    spec_q = shlex.quote(f"{commit}:{f.path}")

    if f.kind == ChangeKind.DELETED:
        return [
            f"# delete {f.path}",
            f"rm -f -- {path_q}",
        ]

    parent = str(Path(f.path).parent)
    cmds: list[str] = [f"# {f.kind.value} {f.path}"]
    if parent not in ("", "."):
        cmds.append(f"mkdir -p -- {shlex.quote(parent)}")
    cmds.append(f"git -C {main_q} show {spec_q} > {path_q}")
    return cmds


def assemble_stage_commands(data: dict[str, Any], synced: set[str]) -> str:
    """Build ``git add`` / ``git rm`` lines for Sync-checked paths."""
    adds: list[str] = []
    rms: list[str] = []
    for f in data["files"]:
        if f["path"] not in synced:
            continue
        if f.get("kind") == ChangeKind.DELETED.value:
            rms.append(f["path"])
        else:
            adds.append(f["path"])
    lines: list[str] = []
    if adds:
        lines.append("git add -- " + " ".join(shlex.quote(p) for p in adds))
    if rms:
        lines.append("git rm -- " + " ".join(shlex.quote(p) for p in rms))
    if not lines:
        return "# No Sync-checked files to stage.\n"
    return "\n".join(lines) + "\n"


def commit_message_body(data: dict[str, Any]) -> str:
    """Body under the feature-name subject: full message or bullet subjects."""
    subjects = data.get("subjects") or []
    if len(subjects) <= 1:
        msg = data.get("commit_message") or (subjects[0] if subjects else "")
        return msg.rstrip("\n")
    return "\n".join(f"- {s}" for s in subjects)


def assemble_commit_message_text(
    data: dict[str, Any], feature_name: str = ""
) -> str:
    """
    Full ``git commit -m …`` command.

    *feature_name* is the first line (subject). Defaults to ``Feature name``
    when empty so the command stays copyable before the user types.
    """
    feature = feature_name.strip() or "Feature name"
    body = commit_message_body(data)
    full = f"{feature}\n\n{body}" if body else feature
    return f"git commit -m {shlex.quote(full)}\n"
